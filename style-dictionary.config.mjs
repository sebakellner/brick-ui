import { formattedVariables } from 'style-dictionary/utils';

const only =
  (...groups) =>
  (token) =>
    groups.includes(token.path[0]);

const cssFile = (destination, filter, selector = ':root') => ({
  destination,
  format: 'css/variables',
  filter,
  options: { selector, outputReferences: true, showFileHeader: false },
});

const hooks = {
  buttonBg: '--bk-button-bg',
  buttonBgHover: '--bk-button-bg-hover',
  buttonFg: '--bk-button-fg',
  buttonBorder: '--bk-button-border',
  buttonBorderHover: '--bk-button-border-hover',
  buttonRadius: '--bk-button-radius',
  inputRadius: '--bk-input-radius',
  checkboxSize: '--bk-checkbox-size',
  checkboxRadius: '--bk-checkbox-radius',
  checkboxVariantSize: '--bk-checkbox-variant-size',
  checkboxVariantRadius: '--bk-checkbox-variant-radius',
  buttonVariantBg: '--bk-button-variant-bg',
  buttonVariantBgHover: '--bk-button-variant-bg-hover',
  buttonVariantFg: '--bk-button-variant-fg',
  buttonVariantBorder: '--bk-button-variant-border',
};

const camel = (path) =>
  path
    .flatMap((part) => part.split('-'))
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');

const THEMED = (token) => token.path[0] === 'role-light' || token.path[0] === 'role-dark';

const platform = (files, transforms = []) => ({
  transformGroup: 'css',
  transforms,
  prefix: 'bk',
  buildPath: 'src/styles/tokens/',
  files,
});

const LIGHT_ROLES = ':where(:root), :where([data-theme="light"])';
const DARK_ROLES = ':where([data-theme="dark"])';
const DARK_ROLES_AUTO = ':where(:root:not([data-theme]))';

export default {
  source: ['tokens/**/*.json'],
  hooks: {
    transforms: {
      'name/strip-theme': {
        type: 'name',
        filter: THEMED,
        transform: (token) => `bk-${token.path.slice(1).join('-')}`,
      },
    },
    formats: {
      'typescript/token-names': ({ dictionary }) => {
        const entries = dictionary.allTokens
          .map((token) => `  ${camel(token.path)}: '--${token.name}',`)
          .join('\n');
        return [
          '// Generated by style-dictionary from tokens/*.json. Do not edit.',
          'export const tokens = {',
          entries,
          '} as const;',
          '',
          'export type TokenName = (typeof tokens)[keyof typeof tokens];',
          '',
          'export const hooks = {',
          Object.entries(hooks)
            .map(([key, value]) => `  ${key}: '${value}',`)
            .join('\n'),
          '} as const;',
          '',
          'export type HookName = (typeof hooks)[keyof typeof hooks];',
          '',
        ].join('\n');
      },
      'css/variables-in-media': ({ dictionary, options }) => {
        const body = formattedVariables({
          format: 'css',
          dictionary,
          outputReferences: options.outputReferences,
        })
          .split('\n')
          .map((line) => (line ? `  ${line}` : line))
          .join('\n');
        return [
          '@media (prefers-color-scheme: dark) {',
          `  ${options.selector} {`,
          body,
          '  }',
          '}',
          '',
        ].join('\n');
      },
    },
  },
  platforms: {
    space: platform([cssFile('space.css', only('space'))]),
    rounded: platform([cssFile('rounded.css', only('radius'))]),
    color: platform(
      [cssFile('color.css', only('palette', 'role-light'), LIGHT_ROLES)],
      ['name/strip-theme'],
    ),
    colorDark: platform(
      [cssFile('color.dark.css', only('role-dark'), DARK_ROLES)],
      ['name/strip-theme'],
    ),
    colorDarkAuto: platform(
      [
        {
          destination: 'color.dark.media.css',
          format: 'css/variables-in-media',
          filter: only('role-dark'),
          options: {
            selector: DARK_ROLES_AUTO,
            outputReferences: true,
            showFileHeader: false,
          },
        },
      ],
      ['name/strip-theme'],
    ),
    control: platform([cssFile('control.css', only('button'))]),
    typography: platform([
      cssFile('typography.css', only('font', 'font-size', 'font-weight', 'line-height')),
    ]),
    typescript: {
      transformGroup: 'css',
      transforms: ['name/strip-theme'],
      prefix: 'bk',
      buildPath: 'src/styles/',
      files: [{ destination: 'tokens.generated.ts', format: 'typescript/token-names' }],
    },
    base: platform([
      cssFile(
        'base.css',
        only(
          'border-width',
          'control-height',
          'transition',
          'focus-ring-width',
          'focus-ring-offset',
        ),
      ),
    ]),
  },
};
